-- Ejecutar con psql como un usuario con permisos para crear bases de datos.
-- Si la base ya existe, psql no ejecutará la primera línea.
SELECT 'CREATE DATABASE "catalogoMotos"'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'catalogoMotos')\gexec

\connect "catalogoMotos"

CREATE TABLE administrador (
    identificador INTEGER GENERATED BY DEFAULT AS IDENTITY,
    usuario VARCHAR(255),
    contrasena VARCHAR(255)
);

CREATE TABLE moto (
    identificador INTEGER GENERATED BY DEFAULT AS IDENTITY,
    modelo VARCHAR(100),
    marca VARCHAR(255),
    categoria VARCHAR(50),
    cilindrada INTEGER,
    precio NUMERIC(10, 2),
    imagenlink VARCHAR(500),
    stock INTEGER,
    descripcion VARCHAR(1000)
);
